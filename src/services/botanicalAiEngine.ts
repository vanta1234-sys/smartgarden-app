function cleanBotanicalTopic(topic: string): string {
  return topic
    .replace(/^καλλιεργεια\s+/i, "")
    .replace(/^πως να φυτεψετε\s+/i, "")
    .replace(/^πως να καλλιεργησετε\s+/i, "")
    .replace(/^πως να φροντισετε\s+/i, "")
    .replace(/^φροντιδα\s+/i, "")
    .replace(/^οδηγος\s+/i, "")
    .replace(/\s+σε γλαστρα/i, "")
    .replace(/\s+στο μπαλκονι/i, "")
    .replace(/\s+στον κηπο/i, "")
    .trim();
}

